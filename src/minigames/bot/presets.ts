/** Применяет сценарий: тексты — из библиотеки, имя, ссылки, цена и кризисный текст — игрока. */
export function applyPreset(cfg: BotConfig, preset: BotPreset): BotConfig {
  return {
    ...cfg,
    welcome: preset.welcome,
    consent: true,
    consentText: cfg.consentText.trim() ? cfg.consentText : DEFAULT_CONSENT_TEXT,
    leadMagnetTitle: preset.leadMagnetTitle,
    quiz: preset.quiz.map((q, i) => ({ id: `${preset.id}-q${i + 1}`, text: q.text, options: [...q.options] })),
    offerText: preset.offerText,
    bookingText: preset.bookingText,
    followUp: preset.followUp,
    crisisText: cfg.crisisText.trim() ? cfg.crisisText : DEFAULT_CRISIS_TEXT,
  }
}
