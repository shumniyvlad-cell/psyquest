// Распознавание кризисных сообщений. Ложная тревога лучше пропущенного человека,
// поэтому маркеры ловят словоформы и перестановки, а не точные фразы.

/** Нижний регистр, ё → е, пунктуация → пробелы, пробелы схлопнуты. */
export function normalizeCrisisText(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9\s]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

interface Marker {
  label: string
  re: RegExp
}

// Все выражения работают по нормализованному тексту: только буквы, цифры и одиночные пробелы.
// \b в JS не понимает кириллицу, поэтому границы слов — через lookbehind/lookahead.
const S = '(?<![а-яa-z])'
const END = '(?![а-яa-z])'
const r = (src: string) => new RegExp(src)

const WANT = '(?:хочу|хочется|хотелось|хочет|хотела|хотел|хотим)'
const FILL = '(?:(?:очень|совсем|больше|уже|вообще|особо|так|дальше|просто|сейчас) )*'

const MARKERS: Marker[] = [
  { label: 'суицид', re: r(`${S}су[иеы]ц[иеы]д`) },
  {
    label: 'не хочу жить',
    re: r(`${S}не ${FILL}${WANT} ${FILL}жить${END}|${S}жить ${FILL}не ${FILL}${WANT}${END}`),
  },
  {
    label: 'покончить с собой',
    re: r(`${S}поконч[а-я]* (?:бы )?(?:с собой|с жизнью|со всем${END})|${S}свест?[а-я]* сч[е]ты с жизнью|${S}свед[а-я]* сч[е]ты`),
  },
  {
    label: 'убить себя',
    re: r(`${S}(?:убить|убью|убиваю|убьешь|убил|убила|убивать) себя|${S}себя (?:убить|убью|убиваю)${END}|${S}(?:убиться|убьюсь)${END}`),
  },
  { label: 'самоповреждение', re: r(`самоповрежд|${S}селф ?харм|${S}self ?harm`) },
  {
    label: 'порезать себя',
    re: r(
      `${S}(?:по)?(?:рез|реж)[а-я]* (?:себя|себе (?:руки|руку|вены|запясть[а-я]*|кожу))|${S}себя (?:по)?(?:рез|реж)[а-я]*|${S}(?:по)?(?:рез|реж)[а-я]* (?:вены|запясть[а-я]*)|${S}вскр[а-я]* (?:себе )?вены`,
    ),
  },
  {
    label: 'нет смысла жить',
    re: r(
      `${S}нет (?:никакого )?смысла ${FILL}(?:в )?жи(?:ть|зни)${END}|${S}смысла жить ${FILL}нет${END}|${S}жить ${FILL}нет (?:никакого )?смысла|${S}не вижу (?:никакого )?смысла ${FILL}(?:в )?жи(?:ть|зни)${END}|${S}незачем ${FILL}жить${END}|${S}жить ${FILL}незачем${END}|${S}в жизни ${FILL}нет (?:никакого )?смысла|${S}жизнь ${FILL}не имеет смысла`,
    ),
  },
  // Дополнительные формулировки: люди редко пишут «суицид», чаще — вот так.
  {
    label: 'хочу умереть',
    re: r(`${S}${WANT} (?:бы )?${FILL}(?:умереть|сдохнуть|не проснуться|исчезнуть навсегда|не существовать)${END}`),
  },
  { label: 'уйти из жизни', re: r(`${S}(?:уйти|уйду|уйдет) из жизни|${S}выпил(?:иться|юсь|илась|ился)${END}`) },
  { label: 'лучше бы меня не было', re: r(`${S}лучше бы меня не было|${S}лучше бы я не родил|${S}лучше бы я умер`) },
]

/** Человекочитаемый список маркеров — для сценария и подсказок. */
export const CRISIS_MARKERS: readonly string[] = MARKERS.map((m) => m.label)

/** Какой маркер сработал (или null). */
export function findCrisisMarker(text: string): string | null {
  const n = normalizeCrisisText(text)
  if (!n) return null
  for (const m of MARKERS) {
    if (m.re.test(n)) return m.label
  }
  return null
}

export function isCrisisMessage(text: string): boolean {
  return findCrisisMarker(text) !== null
}
