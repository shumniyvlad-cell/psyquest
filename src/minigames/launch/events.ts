import type { ActionId } from './simulation.ts'

export interface EventCtx {
  day: number
  days: number
  energyRatio: number
  interest: number
  picks: readonly ActionId[]
  applications: number
  target: number
}

export interface EventEffect {
  energy?: number
  interest?: number
  /** Доверие аудитории: каждая единица меняет отклик на предложения на 7% */
  trust?: number
  /** Гарантированные заявки */
  apps?: number
  /** Шанс получить ещё одну заявку */
  appsChance?: number
  /** Сегодняшние дела отменяются и становятся отдыхом */
  cancel?: boolean
  /** Множитель восстановления от отдыха сегодня (вынужденный отдых восстанавливает хуже планового) */
  restMult?: number
  /** Множитель отдачи сегодняшних дел */
  mult?: number
  /** Множитель отдачи эфиров сегодня */
  liveMult?: number
  /** Дополнительный расход энергии на сегодняшние дела */
  extraCost?: number
  /** Множители на завтра */
  next?: { interest?: number; dm?: number; apps?: number }
}

export interface EventOption {
  label: string
  result: string
  effect: EventEffect
  /** Бережное решение — в пользу себя, клиентов и профессии */
  wise?: boolean
}

export interface StormEvent {
  id: string
  title: string
  text: string
  tone: 'bad' | 'good' | 'mixed'
  options: EventOption[]
  weight: (c: EventCtx) => number
}

