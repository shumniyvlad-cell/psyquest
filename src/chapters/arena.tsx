function SalesScript({ api }: { api: StepApi }) {
  const saved = useGame((s) => s.artifacts.sales)
  const setArtifact = useGame((s) => s.setArtifact)
  const gainXp = useGame((s) => s.gainXp)
  const [steps, setSteps] = useState<SalesStep[]>(() => saved?.steps ?? defaults())
  const save = (next: SalesStep[]) => {
    setSteps(next)
    setArtifact('sales', { steps: next })
  }
  const ready = steps.every((x) => x.text.trim().length > 10)
  return (
    <div className="workbench">
      <ol className="ar-script">
        {steps.map((st, i) => (
          <li key={st.id} className="panel panel-pad workbench-card">
            <div className="row">
              <span className="fg-step num">{i + 1}</span>
              <h3 className="display t-20">{st.title}</h3>
            </div>
            <textarea
              className="textarea"
              rows={3}
              value={st.text}
              onChange={(e) => save(steps.map((x, j) => (j === i ? { ...x, text: e.target.value } : x)))}
              aria-label={st.title}
            />
          </li>
        ))}
      </ol>
      <div className="panel panel-pad workbench-card">
        <p className="small muted">
          Правило Арены: не больше трети встречи говоришь ты. Остальное — вопросы и внимательное молчание. Цена звучит один раз, спокойно, без извинений.
        </p>
        <MentorBox task="sales" draft={steps.map((x) => `${x.title}: ${x.text}`).join('\n')} context={{}} />
      </div>
      <StepFooter
        canGo={ready}
        onGo={() => {
          setArtifact('sales', { steps })
          if (!api.replay) gainXp(110, 'сценарий диагностики')
          api.done()
        }}
        label="Выйти на арену"
      />
    </div>
  )
}

