function Dossier({ api }: { api: StepApi }) {
  const saved = useGame((s) => s.artifacts.expertise)
  const setArtifact = useGame((s) => s.setArtifact)
  const gainXp = useGame((s) => s.gainXp)
  const [d, setD] = useState<ExpertiseArtifact>(saved ?? EMPTY)

  const filled = FIELDS.filter((f) => d[f.key].trim().length >= 6).length
  const ready = filled >= 4

  const set = (k: keyof ExpertiseArtifact, v: string) => {
    const next = { ...d, [k]: v }
    setD(next)
    setArtifact('expertise', next)
  }

  const finish = () => {
    setArtifact('expertise', d)
    if (!api.replay) gainXp(80, 'досье экспертизы')
    api.done()
  }

  return (
    <div className="workbench">
      <div className="panel panel-pad workbench-card">
        <div className="spread">
          <span className="row small">
            <Shield size={18} className="gold" /> Прочность щита
          </span>
          <span className="small num muted">{filled} из 6</span>
        </div>
        <Bar value={filled} max={6} />
        <p className="small faint">Нужно хотя бы 4 поля. Каждый факт станет ответом Самозванцу — он прочитает их прямо в бою.</p>
      </div>

      <div className="panel panel-pad workbench-card">
        {FIELDS.map((f) => (
          <Field key={f.key} label={f.label} hint={f.hint} htmlFor={`dos-${f.key}`}>
            {f.long ? (
              <textarea
                id={`dos-${f.key}`}
                className="textarea"
                rows={3}
                value={d[f.key]}
                placeholder={f.placeholder}
                onChange={(e) => set(f.key, e.target.value)}
              />
            ) : (
              <input
                id={`dos-${f.key}`}
                className="input"
                value={d[f.key]}
                placeholder={f.placeholder}
                onChange={(e) => set(f.key, e.target.value)}
              />
            )}
          </Field>
        ))}
        <HintReveal id="doubt_dossier" items={EXAMPLES} />
        <MentorBox
          task="free"
          label="Разбор Совы: насколько убедительно звучит"
          draft={FIELDS.map((f) => `${f.label}: ${d[f.key]}`).join('\n')}
          context={{ goal: 'досье экспертизы психолога для уверенности и текстов «обо мне»' }}
        />
      </div>

      <StepFooter canGo={ready} onGo={finish} label="Выковать щит" note={ready ? 'Этого хватит, чтобы дать бой.' : 'Заполни ещё немного — щит пока тонковат.'} />
    </div>
  )
}

