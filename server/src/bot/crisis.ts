// Кризис-маркеры в свободном тексте лида. Ложная тревога лучше пропущенного человека.
// MARKERS — копия эталона из src/minigames/bot/crisis.ts (что ловит превью, ловит и живой бот);
// EXTRA — серверные дополнения: ещё формулировки, которые встречаются в переписке.

/** Нижний регистр, ё → е, пунктуация → пробелы, пробелы схлопнуты (как в превью). */
export function normalizeCrisisText(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9\s]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

// \b в JS не понимает кириллицу, поэтому границы слов — через lookbehind/lookahead
const S = '(?<![а-яa-z])'
const END = '(?![а-яa-z])'
const r = (src: string) => new RegExp(src)

const WANT = '(?:хочу|хочется|хотелось|хочет|хотела|хотел|хотим)'
const FILL = '(?:(?:очень|совсем|больше|уже|вообще|особо|так|дальше|просто|сейчас) )*'

const MARKERS: RegExp[] = [
  // суицид
  r(`${S}су[иеы]ц[иеы]д`),
  // не хочу жить
  r(`${S}не ${FILL}${WANT} ${FILL}жить${END}|${S}жить ${FILL}не ${FILL}${WANT}${END}`),
  // покончить с собой
  r(`${S}поконч[а-я]* (?:бы )?(?:с собой|с жизнью|со всем${END})|${S}свест?[а-я]* сч[е]ты с жизнью|${S}свед[а-я]* сч[е]ты`),
  // убить себя
  r(`${S}(?:убить|убью|убиваю|убьешь|убил|убила|убивать) себя|${S}себя (?:убить|убью|убиваю)${END}|${S}(?:убиться|убьюсь)${END}`),
  // самоповреждение
  r(`самоповрежд|${S}селф ?харм|${S}self ?harm`),
  // порезать себя
  r(
    `${S}(?:по)?(?:рез|реж)[а-я]* (?:себя|себе (?:руки|руку|вены|запясть[а-я]*|кожу))|${S}себя (?:по)?(?:рез|реж)[а-я]*|${S}(?:по)?(?:рез|реж)[а-я]* (?:вены|запясть[а-я]*)|${S}вскр[а-я]* (?:себе )?вены`,
  ),
  // нет смысла жить
  r(
    `${S}нет (?:никакого )?смысла ${FILL}(?:в )?жи(?:ть|зни)${END}|${S}смысла жить ${FILL}нет${END}|${S}жить ${FILL}нет (?:никакого )?смысла|${S}не вижу (?:никакого )?смысла ${FILL}(?:в )?жи(?:ть|зни)${END}|${S}незачем ${FILL}жить${END}|${S}жить ${FILL}незачем${END}|${S}в жизни ${FILL}нет (?:никакого )?смысла|${S}жизнь ${FILL}не имеет смысла`,
  ),
  // хочу умереть
  r(`${S}${WANT} (?:бы )?${FILL}(?:умереть|сдохнуть|не проснуться|исчезнуть навсегда|не существовать)${END}`),
  // уйти из жизни
  r(`${S}(?:уйти|уйду|уйдет) из жизни|${S}выпил(?:иться|юсь|илась|ился)${END}`),
  // лучше бы меня не было
  r(`${S}лучше бы меня не было|${S}лучше бы я не родил|${S}лучше бы я умер`),
]

const EXTRA: RegExp[] = [
  r(`${S}самоубий|${S}suicid|${S}kill myself|${S}want to die|${S}end my life`),
  r(`${S}не (?:осталось|видно) (?:никакого )?смысла ${FILL}(?:в )?жи(?:ть|зни)${END}`),
  r(`${S}жизнь ${FILL}(?:потеряла|утратила) смысл|${S}жизнь ${FILL}бессмысленн`),
  r(`${S}не для (?:чего|кого) ${FILL}жить${END}|${S}устал[а-я]* ${FILL}жить${END}`),
  r(`${S}повес(?:иться|илась|ился)${END}|${S}повеш(?:усь|аюсь)${END}`),
  r(`${S}лучше (?:бы )?(?:уже )?(?:умереть|сдохнуть)${END}|${S}лучше без меня${END}|${S}меня (?:скоро )?не станет${END}`),
  r(`${S}наглота[а-я]* (?:таблеток|таблетками|колес)`),
  r(`${S}(?:спрыгн|прыгн|сброс|сброш|выброс|выброш|шагн)[а-я]* (?:с|со|из) (?:крыши|окна|моста|балкона)`),
  r(`${S}не ${FILL}${WANT} ${FILL}просыпаться${END}`),
  r(`${S}(?:думаю|думать|мысли|мысль) о смерти${END}`),
]

export function hasCrisisMarkers(text: string): boolean {
  const n = normalizeCrisisText(text)
  if (!n) return false
  return MARKERS.some((re) => re.test(n)) || EXTRA.some((re) => re.test(n))
}
